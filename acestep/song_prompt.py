"""Build explicit music captions without inventing lyrics or promising audio quality."""
import json
from pathlib import Path
from uuid import uuid4

import gradio as gr


PRESETS = {
    "Melodic guitar metal": ("mid-tempo melodic death metal with neoclassical lead guitar",
        "electric-guitar-led intro, harmonized twin leads, harmonic-minor runs, sweep arpeggios, "
        "palm-muted rhythm guitars, electric bass and acoustic drums",
        "dark, defiant, triumphant", "prominent clean female lead singing the supplied English lyrics",
        "guitar intro, contrasting verses and repeated choruses, bridge, final chorus; "
        "only two brief high-register female screams near the end",
        "guitars in front, clear vocal diction, natural drum attack, distinct instruments"),
    "Female melodic metal": ("melodic metal", "distorted rhythm guitars, electric bass, acoustic drums",
        "resilient, emotional", "expressive female alto, clear diction, restrained vibrato",
        "intimate verse, powerful chorus", "clear separation, natural dynamics, warm lead vocal"),
    "Acoustic cover backing": ("acoustic ballad", "steel-string acoustic guitar",
        "warm, intimate", "", "gentle verse, fuller chorus", "close acoustic recording, room ambience"),
    "Piano cover backing": ("piano ballad", "solo grand piano",
        "reflective, emotional", "", "sparse verse, fuller chorus", "natural piano resonance, soft dynamics"),
}


def build_caption(genre, instruments, mood, voice, delivery, production, instrumental):
    """Return a bounded caption and a transparent record of the user's choices."""
    fields = dict(genre=genre, instruments=instruments, mood=mood, voice=voice,
                  delivery=delivery, production=production)
    fields = {key:str(value or "").strip() for key,value in fields.items()}
    if any(len(value)>500 for value in fields.values()):
        raise gr.Error("Keep each description under 500 characters.")
    if not fields["genre"] or not fields["instruments"]:
        raise gr.Error("Describe the genre and instruments first.")
    parts = [fields["genre"],fields["mood"],fields["instruments"]]
    if instrumental:
        parts.append("instrumental accompaniment, space for a live singer")
        fields["voice"] = ""
    else:
        parts.append(fields["voice"])
    parts.extend([fields["delivery"],fields["production"]])
    caption = ". ".join(part for part in parts if part)+"."
    if len(caption)>1800:
        raise gr.Error("Shorten the description to focus on the most important musical details.")
    return caption,dict(fields,instrumental=bool(instrumental))


def apply_caption(*args):
    """Save a recipe and update only the caption and instrumental toggle."""
    caption,recipe = build_caption(*args)
    folder = Path(__file__).resolve().parents[1]/"acestep_output/prompt-recipes"
    folder.mkdir(parents=True,exist_ok=True)
    destination = folder/f"{uuid4().hex}.json"
    destination.write_text(json.dumps(dict(recipe,caption=caption),indent=2),encoding="utf-8")
    return caption,bool(args[-1]),str(destination),(
        "Caption applied. Your lyrics are unchanged. Choose Custom for a new song, then Generate Music. "
        "For a cover, choose Remix and supply Source Audio. Instrument choices and natural vocals "
        "are requests to the model, not guarantees. No audio has been generated by this button.")


def load_preset(name):
    """Return editable defaults; never change the user's actual lyrics."""
    if name not in PRESETS:
        raise gr.Error("Choose a prompt preset.")
    return (*PRESETS[name],name in {"Acoustic cover backing","Piano cover backing"})


def build_song_prompt(captions, instrumental_checkbox):
    """Offer a small caption builder connected to the real generation inputs."""
    with gr.Accordion("✨ Help me describe my song",open=False):
        gr.Markdown("Pick a starting point, adjust it, then press **Apply**.")
        preset = gr.Dropdown(list(PRESETS),value="Melodic guitar metal",label="Starting point")
        load = gr.Button("Load starting point into builder")
        defaults = PRESETS["Melodic guitar metal"]
        fields = [gr.Textbox(value=value,label=label) for value,label in zip(defaults,
            ("Genre","Instruments","Mood","Voice","Delivery / arrangement","Production"))]
        instrumental = gr.Checkbox(value=False,label="Instrumental backing for me to sing over")
        preview = gr.Button("Preview prompt")
        text = gr.Textbox(label="Prompt preview",interactive=False,lines=4)
        recipe = gr.JSON(visible=False)
        apply = gr.Button("Apply to Music Caption")
        download = gr.File(label="Saved prompt recipe")
        status = gr.Textbox(label="Prompt status",interactive=False)
        load.click(load_preset,preset,[*fields,instrumental])
        preview.click(build_caption,[*fields,instrumental],[text,recipe])
        apply.click(apply_caption,[*fields,instrumental],[captions,instrumental_checkbox,download,status])
